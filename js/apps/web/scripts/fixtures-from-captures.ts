// Turn the recorded devnet runs in captures/ into lib/recorded.ts, the replay the dashboard and landing page play.
//   node scripts/fixtures-from-captures.ts
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const CAPTURES = join(import.meta.dirname, '../../../../captures')
const SOURCES = { scene1: '2026-10-28-devnet-scene1', scenes23: '2026-10-28-devnet-scenes2-3' }

type Ev = Record<string, any> & { kind: string, at: number }
const read = (dir: string): Ev[] => readFileSync(join(CAPTURES, dir, 'events.jsonl'), 'utf8').trim().split('\n').map(l => JSON.parse(l))

/** Events of scene n, with payment ids made unique across runs (each run numbers its own from pay-1). */
function scene (events: Ev[], n: number): Array<{ dt: number, e: Record<string, any> }> {
  const start = events.findIndex(e => e.kind === 'scene' && e.n === n && e.state === 'start')
  const end = events.findIndex((e, i) => i > start && e.kind === 'scene' && e.n === n && e.state !== 'start')
  const id = (v: string): string => v.replace(/^pay-\d+$/, `pay-s${n}`)
  return events.slice(start, end + 1).map((e, i, all) => {
    const { seq: _s, at: _a, ...body } = e
    if (typeof body.paymentId === 'string') body.paymentId = id(body.paymentId)
    if (typeof body.requestId === 'string') body.requestId = id(body.requestId)
    if (body.kind === 'payment') body.id = id(body.id)
    return { dt: i === 0 ? 0 : e.at - all[i - 1].at, e: body }
  })
}

const one = read(SOURCES.scene1)
const two = read(SOURCES.scenes23)
// Standing peers from the second run: it had every role up (agent, seller, provider, Kubo, relay).
const peers = two.filter(e => e.kind === 'peer').map((e, i) => {
  const { seq: _s, at: _a, ...body } = e
  return { dt: i === 0 ? 0 : 60, e: body }
})

const out = `// Generated by scripts/fixtures-from-captures.ts from captures/${SOURCES.scene1} and captures/${SOURCES.scenes23}.
// Real devnet runs of 2026-10-28: real keys, CIDs, memos and transaction signatures. Do not edit by hand.
import type { SwarmEventBody } from '@swarm/events'

type Recorded = Array<{ dt: number, e: SwarmEventBody }>

export const RECORDED_PEERS: Recorded = ${JSON.stringify(peers, null, 2)}

export const RECORDED_SCENE1: Recorded = ${JSON.stringify(scene(one, 1), null, 2)}

export const RECORDED_SCENE2: Recorded = ${JSON.stringify(scene(two, 2), null, 2)}

export const RECORDED_SCENE3: Recorded = ${JSON.stringify(scene(two, 3), null, 2)}
`
writeFileSync(join(import.meta.dirname, '../lib/recorded.ts'), out)
console.log(`lib/recorded.ts: ${peers.length} peers, scenes of ${scene(one, 1).length}, ${scene(two, 2).length}, ${scene(two, 3).length} events`)
